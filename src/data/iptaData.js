export function findIPTAByUniv(univStr) {
  if (!univStr) return null;
  const lower = univStr.toLowerCase();
  return ALL_IPTA.find(
    (ipta) =>
      lower.includes(ipta.code.toLowerCase()) ||
      lower.includes(ipta.fullName.toLowerCase()) ||
      lower.includes(ipta.shortName.toLowerCase()) ||
      lower.includes(ipta.id)
  ) || null;
}

export const IPTA_NAMES = ALL_IPTA.map((ipta) => `${ipta.fullName} (${ipta.code})`);

