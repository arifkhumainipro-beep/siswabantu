  static IPTAModel? findByUnivString(String univ) {
    final lower = univ.toLowerCase();
    for (final ipta in allIPTA) {
      if (lower.contains(ipta.code.toLowerCase()) ||
          lower.contains(ipta.fullName.toLowerCase()) ||
          lower.contains(ipta.shortName.toLowerCase())) {
        return ipta;
      }
    }
    return null;
  }
